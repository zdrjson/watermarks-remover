# ---------------------------------------------------------------------------
# SPEC item 1: zero-width characters in a .md file
# ---------------------------------------------------------------------------


class TestZeroWidthMarkdown(TempDirTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.md_path = self.tmp_path / "note.md"
        self.visible_text = write_zero_width_markdown(self.md_path)
        self.original_hash = sha256_of(self.md_path)

    def test_scan_detects_zero_width_characters(self) -> None:
        result = core.scan_file(self.md_path)
        self.assertIsNone(result.error)
        self.assertIsInstance(result.path, Path)
        self.assertTrue(result.actionable)
        self.assertTrue(result.findings, "expected at least one finding")
        self.assertTrue(
            any("隐形字符" in f for f in result.findings),
            f"expected a finding mentioning 隐形字符 (SPEC rule 6), got: {result.findings}",
        )
        # The exact kind label is upstream-defined (SPEC only gives examples);
        # we only require it identifies a real, recognized format.
        self.assertNotEqual(result.kind, "unknown")

    def test_clean_strips_zero_width_and_preserves_visible_text(self) -> None:
        result = core.clean_file(self.md_path)
        self.assertTrue(result.ok, result.message)
        self.assertIsNotNone(result.output)
        assert result.output is not None  # narrows type for the checks below
        self.assertTrue(result.output.exists())
        self.assertEqual(result.output.name, "note_已清理.md")

        cleaned_text = result.output.read_text(encoding="utf-8")
        for ch in ZERO_WIDTH_CHARS:
            self.assertNotIn(ch, cleaned_text, f"zero-width char {ch!r} survived cleaning")
        self.assertEqual(cleaned_text, self.visible_text)

    def test_clean_does_not_modify_original_file(self) -> None:
        core.clean_file(self.md_path)
        self.assertEqual(sha256_of(self.md_path), self.original_hash)


