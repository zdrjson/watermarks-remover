# ---------------------------------------------------------------------------
# Shared fixture helpers
#
# Every fixture is built fresh, in a per-test tempdir, from first principles
# (raw bytes / raw text) - no binary blobs are read from disk or checked into
# the repo, per SPEC.md's instruction that fixtures live only in tempdir.
#
# All zero-width / invisible codepoints below are written as explicit
# \uXXXX escapes (never as literal invisible characters pasted into this
# source file) so the exact codepoints used are unambiguous on inspection.
# ---------------------------------------------------------------------------

ZERO_WIDTH_CHARS = (chr(0x200B), chr(0x2060), chr(0xFEFF))  # ZWSP, WORD JOINER, ZWNBSP/BOM

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def sha256_of(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_zero_width_markdown(path: Path) -> str:
    """Write a .md fixture mixing U+200B / U+2060 / U+FEFF into ordinary
    Chinese/English prose (no frontmatter, no code fences).

    Returns the *visible* text: the same content with every injected
    zero-width character removed, i.e. exactly what a correct cleaner should
    produce as output (this repo's markdown cleaner does not otherwise touch
    plain paragraph text -- no frontmatter or embedded data URIs are present
    in this fixture).
    """
    visible_parts = [
        "# 测试文档\n\n这是一段正常的中文测试文本，用来验证隐藏水印检测功能是否正常工作。\n",
        "This is a normal English sentence mixed in for good measure.\n",
        "再来一句中文收尾，用来确认清理后可见文字完全不变。\n",
    ]
    raw = (
        visible_parts[0]
        + chr(0x200B) * 2
        + visible_parts[1]
        + chr(0x2060)
        + visible_parts[2]
        + chr(0xFEFF)
    )
    path.write_text(raw, encoding="utf-8")
    return "".join(visible_parts)


def write_clean_txt(path: Path) -> str:
    text = (
        "这是一份完全干净的文本文件，没有任何隐藏字符或水印痕迹。\n"
        "Just plain, boring ASCII and CJK text with nothing suspicious in it.\n"
    )
    path.write_text(text, encoding="utf-8")
    return text


def _crc32_bytes(ctype: bytes, payload: bytes) -> bytes:
    return struct.pack(">I", zlib.crc32(ctype + payload) & 0xFFFFFFFF)


def _png_chunk(ctype: bytes, payload: bytes) -> bytes:
    return struct.pack(">I", len(payload)) + ctype + payload + _crc32_bytes(ctype, payload)


def build_minimal_png(with_text_chunk: bool = True) -> bytes:
    """Hand-build a minimal, spec-legal 1x1 8-bit grayscale PNG:
    signature + IHDR + (tEXt) + IDAT + IEND, with correct chunk CRCs.

    When with_text_chunk is True, the tEXt chunk's value contains an
    AI-provenance phrase ("Generated by ...") that this repo's PNG inspector
    recognizes as an AI/provenance hint, without also containing a
    C2PA-specific marker -- so the fixture should scan as actionable via
    generic image-metadata detection, not specifically the C2PA branch.
    """
    ihdr_payload = struct.pack(">IIBBBBB", 1, 1, 8, 0, 0, 0, 0)  # 1x1 px, 8-bit, grayscale
    raw_scanline = bytes([0, 0])  # filter-type byte (0=None) + one gray pixel
    idat_payload = zlib.compress(raw_scanline)

    parts = [PNG_SIGNATURE, _png_chunk(b"IHDR", ihdr_payload)]
    if with_text_chunk:
        text_payload = b"Comment\x00Generated by an AI image tool, for testing purposes only."
        parts.append(_png_chunk(b"tEXt", text_payload))
    parts.append(_png_chunk(b"IDAT", idat_payload))
    parts.append(_png_chunk(b"IEND", b""))
    return b"".join(parts)


def parse_png_chunks(data: bytes) -> list[tuple[bytes, bytes]]:
    """Parse PNG bytes into a list of (chunk_type, payload) tuples, asserting
    along the way that the file is structurally legal: correct signature,
    IHDR first with unmodified 1x1 dimensions, every chunk's CRC32 correct,
    and IEND present as the last chunk.

    Used both to validate our own fixture and to validate a cleaned PNG that
    core.clean_file() produced.
    """
    assert data[:8] == PNG_SIGNATURE, "missing/invalid PNG signature"
    pos = 8
    chunks: list[tuple[bytes, bytes]] = []
    while pos + 8 <= len(data):
        length = struct.unpack(">I", data[pos : pos + 4])[0]
        ctype = data[pos + 4 : pos + 8]
        payload_start = pos + 8
        payload_end = payload_start + length
        payload = data[payload_start:payload_end]
        crc_bytes = data[payload_end : payload_end + 4]
        assert len(crc_bytes) == 4, f"truncated chunk {ctype!r}"
        assert crc_bytes == _crc32_bytes(ctype, payload), f"bad CRC32 for chunk {ctype!r}"
        chunks.append((ctype, payload))
        pos = payload_end + 4
        if ctype == b"IEND":
            break
    assert chunks, "no chunks parsed"
    assert chunks[0][0] == b"IHDR", "IHDR must be the first chunk"
    assert chunks[0][1][:8] == struct.pack(">II", 1, 1), "IHDR pixel dimensions changed"
    assert chunks[-1][0] == b"IEND", "IEND must be the last chunk"
    return chunks


# Magic-byte prefixes recognized by this repo's format sniffer (images,
# zip-based containers, PDF). The unknown-format fixture must not collide
# with any of these by chance.
_KNOWN_MAGIC_PREFIXES = (
    PNG_SIGNATURE,
    b"\xff\xd8",  # JPEG
    b"RIFF",  # WebP/AVI container
    b"BM",  # BMP
    b"GIF87a",
    b"GIF89a",
    b"II*\x00",  # TIFF little-endian
    b"MM\x00*",  # TIFF big-endian
    b"II+\x00",  # BigTIFF little-endian
    b"MM\x00+",  # BigTIFF big-endian
    b"PK\x03\x04",  # zip-based containers (docx/xlsx/pptx/odt/epub)
    b"%PDF",
)


def write_random_bytes_file(path: Path, size: int = 256) -> bytes:
    """Write a .xyz fixture of random bytes, deterministic but re-rolled
    (via an incrementing seed) until it does not start with any magic byte
    sequence this repo's classifier would recognize as a known format.
    """
    seed = 0xBADC0DE
    while True:
        data = bytes(random.Random(seed).getrandbits(8) for _ in range(size))
        if not any(data.startswith(prefix) for prefix in _KNOWN_MAGIC_PREFIXES):
            break
        seed += 1
    path.write_bytes(data)
    return data


