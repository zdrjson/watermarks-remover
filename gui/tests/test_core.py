"""Unit tests for gui/core.py — the pure-logic layer of the AI watermark GUI.

These tests are written directly against the public contract documented in
gui/SPEC.md, sections "core.py 公开契约" and "测试规格". They intentionally do
not import gui/app.py (see test_app_smoke.py for that) and do not read
core.py's implementation to shape assertions — the contract in SPEC.md is the
only source of truth. All fixtures are generated on the fly in a tempdir; no
binary fixtures are committed to the repo.

If gui/core.py does not exist yet (e.g. a parallel implementation task is
still in flight), the module-level `import core` below raises ImportError and
every test in this file errors out. That is expected and fine: this file must
still pass `python3 -m py_compile`, and once core.py exists with the
documented contract, these tests should pass unmodified.

Run with:
    cd ~/watermarks-remover && python3 -m unittest discover -s gui/tests -v
"""

