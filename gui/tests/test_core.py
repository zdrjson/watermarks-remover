class TestDefaultOutputPath(TempDirTestCase):
    def test_basic_suffix_no_collision(self) -> None:
        src = self.tmp_path / "photo.png"
        src.write_bytes(b"not-really-a-png")
        out = core.default_output_path(src)
        self.assertEqual(out.parent, src.parent)
        self.assertEqual(out.name, "photo_已清理.png")

    def test_collision_increments_suffix(self) -> None:
        src = self.tmp_path / "photo.png"
        src.write_bytes(b"not-really-a-png")

        (self.tmp_path / "photo_已清理.png").write_bytes(b"already exists")
        out2 = core.default_output_path(src)
        self.assertEqual(out2.name, "photo_已清理_2.png")

        (self.tmp_path / "photo_已清理_2.png").write_bytes(b"also already exists")
        out3 = core.default_output_path(src)
        self.assertEqual(out3.name, "photo_已清理_3.png")

    def test_out_dir_overrides_default_parent(self) -> None:
        src_dir = self.tmp_path / "sub"
        src_dir.mkdir()
        src = src_dir / "note.txt"
        src.write_text("hi", encoding="utf-8")

        out_dir = self.tmp_path / "elsewhere"
        out_dir.mkdir()

        out = core.default_output_path(src, out_dir=out_dir)
        self.assertEqual(out.parent, out_dir)
        self.assertEqual(out.name, "note_已清理.txt")

    def test_out_dir_none_defaults_to_source_directory(self) -> None:
        src = self.tmp_path / "doc.md"
        src.write_text("hi", encoding="utf-8")
        out = core.default_output_path(src, out_dir=None)
        self.assertEqual(out.parent, src.parent)
        self.assertEqual(out.name, "doc_已清理.md")


