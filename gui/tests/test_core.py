# SPEC item 3: PNG with a tEXt metadata chunk
# ---------------------------------------------------------------------------


class TestPngTextChunk(TempDirTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.png_path = self.tmp_path / "image.png"
        png_bytes = build_minimal_png(with_text_chunk=True)
        # Sanity-check our own fixture before handing it to core.py: a parse
        # failure here would be a bug in the test, not the implementation.
        fixture_chunks = parse_png_chunks(png_bytes)
        self.assertIn(b"tEXt", [ctype for ctype, _ in fixture_chunks])
        self.png_path.write_bytes(png_bytes)
        self.original_hash = sha256_of(self.png_path)

    def test_scan_detects_text_chunk_metadata(self) -> None:
        result = core.scan_file(self.png_path)
        self.assertIsNone(result.error)
        self.assertTrue(result.actionable)
        self.assertTrue(result.findings)
        # SPEC rule 6 buckets image-metadata findings as either the generic
        # "EXIF/XMP 元数据" category or, if the implementation treats our
        # AI-provenance phrase as a C2PA-adjacent signal, "C2PA 内容凭证".
        # Both are legal per rule 6; we accept either.
        self.assertTrue(
            any(("元数据" in f) or ("C2PA" in f) for f in result.findings),
            f"expected a metadata/C2PA finding, got: {result.findings}",
        )

    def test_clean_strips_text_chunk_and_stays_valid_png(self) -> None:
        result = core.clean_file(self.png_path)
        self.assertTrue(result.ok, result.message)
        self.assertIsNotNone(result.output)
        assert result.output is not None
        self.assertTrue(result.output.exists())
        self.assertEqual(result.output.name, "image_已清理.png")

        cleaned_bytes = result.output.read_bytes()
        chunks = parse_png_chunks(cleaned_bytes)  # raises AssertionError if malformed
        chunk_types = [ctype for ctype, _ in chunks]
        self.assertIn(b"IHDR", chunk_types)
        self.assertIn(b"IEND", chunk_types)
        self.assertNotIn(b"tEXt", chunk_types)
        self.assertNotIn(b"zTXt", chunk_types)
        self.assertNotIn(b"iTXt", chunk_types)

    def test_clean_does_not_modify_original_file(self) -> None:
        core.clean_file(self.png_path)
        self.assertEqual(sha256_of(self.png_path), self.original_hash)


