class TestUnknownFormat(TempDirTestCase):
    def setUp(self) -> None:
        super().setUp()
        self.xyz_path = self.tmp_path / "mystery.xyz"
        write_random_bytes_file(self.xyz_path)
        self.original_hash = sha256_of(self.xyz_path)

    def test_scan_reports_unknown_kind_or_error(self) -> None:
        result = core.scan_file(self.xyz_path)
        self.assertTrue(
            result.kind == "unknown" or result.error is not None,
            f"expected kind=='unknown' or a populated error, got "
            f"kind={result.kind!r} error={result.error!r}",
        )

    def test_clean_fails_with_chinese_message_and_no_output(self) -> None:
        result = core.clean_file(self.xyz_path)
        self.assertFalse(result.ok)
        self.assertIsNone(result.output)
        self.assertTrue(result.message, "expected a human-readable message")
        self.assertNotIn("Traceback", result.message)
        # SPEC rule 3 quotes a specific message for this case: 「跳过：无法识别
        # 的文件格式」. We check its two key words rather than the full string
        # verbatim, to tolerate minor rewording while still holding the
        # implementation to the documented meaning (not just "any Chinese").
        self.assertIn("跳过", result.message)
        self.assertIn("无法识别", result.message)

    def test_clean_writes_no_new_files(self) -> None:
        core.clean_file(self.xyz_path)
        self.assertEqual(
            sorted(p.name for p in self.tmp_path.iterdir()),
            [self.xyz_path.name],
        )

    def test_clean_does_not_modify_original_file(self) -> None:
        core.clean_file(self.xyz_path)
        self.assertEqual(sha256_of(self.xyz_path), self.original_hash)


