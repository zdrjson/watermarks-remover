"""Frontmatter values that span lines must be value-scanned too.

YAML block scalars (`key: >` / `key: |`), wrapped plain values, and list
items (`key:` + `- item` lines) all carry the value on the lines after the
key. Both inspect_markdown and clean_markdown used to read the value from
the key's own line only, so a phrase like "generated by ChatGPT" hidden in
the continuation lines survived a clean pass. Regression tests for #398.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS = ROOT / "service" / "scripts"
sys.path.insert(0, str(SCRIPTS))

from container_meta import clean_markdown, inspect_markdown


def test_block_scalar_value_with_marker_is_flagged_and_removed():
    md = (
        "---\n"
        "title: My doc\n"
        "description: >\n"
        "  This page was generated by ChatGPT\n"
        "  and reviewed by a human.\n"
        "---\n"
        "# Body\n"
    )
    _c2, has_ai, findings, _d = inspect_markdown(md)
    assert has_ai
    assert any("value hit on description" in f for f in findings)
    cleaned, actions = clean_markdown(md)
    assert "ChatGPT" not in cleaned
    assert "title: My doc" in cleaned
    assert "# Body" in cleaned
    assert any("drop frontmatter key (value hit): description" in a for a in actions)
    # the cleaned document must re-inspect clean
    _c2, has_ai, _findings, _d = inspect_markdown(cleaned)
    assert not has_ai


def test_literal_block_scalar_value_is_scanned():
    md = "---\nsummary: |\n  notes authored by Claude\n  second line\n---\nBody\n"
    _c2, has_ai, findings, _d = inspect_markdown(md)
    assert has_ai
    assert any("value hit on summary" in f for f in findings)
    cleaned, _actions = clean_markdown(md)
    assert "authored by Claude" not in cleaned


def test_list_items_under_key_are_scanned():
    md = "---\ntitle: Keep\nsources:\n  - generated by ChatGPT\n  - human notes\n---\n# Body\n"
    _c2, has_ai, findings, _d = inspect_markdown(md)
    assert has_ai
    assert any("value hit on sources" in f for f in findings)
    cleaned, actions = clean_markdown(md)
    assert "ChatGPT" not in cleaned
    assert "human notes" not in cleaned  # list items follow their dropped parent key
    assert "title: Keep" in cleaned
    assert any("drop frontmatter key (value hit): sources" in a for a in actions)


def test_plain_wrapped_multiline_value_is_scanned():
    md = "---\ndescription: this is a long\n  wrapped value written by Claude\n---\n# Body\n"
    _c2, has_ai, findings, _d = inspect_markdown(md)
    assert has_ai
    assert any("value hit on description" in f for f in findings)
    cleaned, _actions = clean_markdown(md)
    assert "written by Claude" not in cleaned
    assert "# Body" in cleaned


def test_single_line_value_behavior_unchanged():
    md = "---\ndescription: This page was generated by ChatGPT\ntitle: My doc\n---\n# Body\n"
    _c2, has_ai, findings, _d = inspect_markdown(md)
    assert has_ai
    assert any("value hit on description" in f for f in findings)
    cleaned, _actions = clean_markdown(md)
    assert "ChatGPT" not in cleaned
    assert "title: My doc" in cleaned


def test_multiline_values_without_markers_are_kept():
    md = (
        "---\n"
        "description: >\n"
        "  An ordinary multi-line\n"
        "  description about cooking.\n"
        "tags:\n"
        "  - one\n"
        "  - two\n"
        "---\n"
        "Body\n"
    )
    cleaned, _ = clean_markdown(md)
    assert "An ordinary multi-line" in cleaned
    assert "- one" in cleaned and "- two" in cleaned
    _c2, has_ai, _findings, _d = inspect_markdown(md)
    assert not has_ai
